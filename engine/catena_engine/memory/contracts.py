"""Memory uses provider results with evidence; extraction is not fact confirmation."""
from typing import Protocol


class MemoryAdapter(Protocol):
    def extract(self, owner: str, payload: dict) -> dict: ...
    def task(self, owner: str, identity: str) -> dict: ...
    def list(self, owner: str, limit: int) -> dict: ...
    def search(self, owner: str, payload: dict) -> dict: ...
